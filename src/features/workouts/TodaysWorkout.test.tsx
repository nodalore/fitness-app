test('changing sessions asks before discarding modified actuals; starting again restores the saved exercise', async () => {
  const user = userEvent.setup(); setup(); await start(user)
  await user.click(screen.getByRole('button', { name: /Hip Thrust/ }))
  await user.click(screen.getByRole('button', { name: 'Add set' }))
  await user.type(screen.getByLabelText('Set 1 reps'), '8')
  await user.click(screen.getByRole('button', { name: 'Change session' }))
  expect(screen.getByRole('group', { name: 'Discard workout draft' })).toBeVisible()
  await user.click(screen.getByRole('button', { name: 'Keep logging' }))
  expect(screen.getByLabelText('Set 1 reps')).toHaveValue(8)
  await user.click(screen.getByRole('button', { name: 'Change session' }))
  await user.click(screen.getByRole('button', { name: 'Discard workout' }))
  expect(screen.getByLabelText('Choose a saved routine')).toBeVisible()
  await user.click(screen.getByRole('button', { name: /Day 1: Glutes and Hammies/ }))
  await user.click(screen.getByRole('button', { name: /Hip Thrust/ }))
  expect(screen.queryByLabelText('Set 1 reps')).not.toBeInTheDocument()
})
