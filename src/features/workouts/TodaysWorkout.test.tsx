test('skip is reversible, removes exercise only today, adds a named exercise once and Cancel inserts nothing', async () => {
  const before = structuredClone(routine), user = userEvent.setup(); setup(); await start(user)
  await user.click(screen.getByRole('button', { name: /Hip Thrust/ }))
  await user.click(screen.getByRole('button', { name: 'Add set' }))
  await user.type(screen.getByLabelText('Set 1 reps'), '8')
  await user.click(screen.getByRole('button', { name: 'Skip today' }))
  expect(screen.getByText('0 sets logged', { selector: 'span.number' })).toBeVisible()
  expect(screen.queryByRole('table')).not.toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Restore exercise' }))
  expect(screen.getByLabelText('Set 1 reps')).toHaveValue(8)
  expect(screen.getByText('1 set logged', { selector: 'span.number' })).toBeVisible()
  await user.click(screen.getByRole('button', { name: 'Remove today' }))
  expect(screen.queryByRole('button', { name: /Hip Thrust/ })).not.toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Add exercise today' }))
  await user.click(screen.getByRole('button', { name: 'Add to workout' }))
  expect(screen.getByRole('alert')).toHaveTextContent('Enter an exercise name')
  await user.type(screen.getByLabelText("Today's exercise name"), 'Cable kickback')
  await user.click(screen.getByRole('button', { name: 'Add to workout' }))
  expect(screen.getAllByRole('button', { name: /Cable kickback/ })).toHaveLength(1)
  expect(screen.getAllByRole('button', { expanded: true })).toHaveLength(1)
  await user.click(screen.getByRole('button', { name: 'Add exercise today' }))
  await user.type(screen.getByLabelText("Today's exercise name"), 'Not added')
  await user.click(screen.getByRole('button', { name: 'Cancel exercise' }))
  expect(screen.queryByRole('button', { name: /Not added/ })).not.toBeInTheDocument()
  expect(routine).toEqual(before)
})
