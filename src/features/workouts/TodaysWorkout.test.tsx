import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { TodaysWorkout } from './TodaysWorkout'
import { blankExercise } from '../routines/types'
import { testCatalog, testDocument } from '../routines/testFixtures'
const routine = { id: 'saved-a', updated_at: 'exact-version', archived_at: null, document: { ...testDocument, name: 'My glute plan', days: [
  { name: 'Glutes and Hammies', weekday: 1, exercises: [
    { ...blankExercise('Hip Thrust'), planned_sets: [{ reps: 8, load_kg: 30, entered_unit: 'kg' as const }, { reps: 6, load_kg: 40, entered_unit: 'kg' as const }] }, blankExercise('RDLs'),
  ] }, { name: 'Upper A', weekday: 3, exercises: [testDocument.days[0].exercises[0]] },
] } }
const other = { ...routine, id: 'saved-b', document: { ...routine.document, name: 'Another routine' } }
function setup(unit: 'kg' | 'lb' = 'kg') { return render(<TodaysWorkout routines={[routine, other, { ...routine, id: 'archived', archived_at: 'old', document: { ...routine.document, name: 'Archived plan' } }]} catalog={testCatalog.map((item, index) => index === 2 ? { ...item, loading_mode: 'per_implement' as const } : item)} defaultUnit={unit} />) }
async function start(user: ReturnType<typeof userEvent.setup>) {
  await user.selectOptions(screen.getByLabelText('Choose a saved routine'), routine.id)
  await user.click(screen.getByRole('button', { name: /Day 1: Glutes and Hammies/ }))
}
test('explicit routine/session choices show original session names, no automatic weekday or archived plan', async () => {
  const user = userEvent.setup(); setup()
  expect(screen.getByLabelText('Choose a saved routine')).toHaveValue('')
  expect(screen.queryByRole('group', { name: "Choose today's session" })).not.toBeInTheDocument()
  expect(screen.queryByRole('option', { name: 'Archived plan' })).not.toBeInTheDocument()
  await user.selectOptions(screen.getByLabelText('Choose a saved routine'), other.id)
  expect(screen.getByRole('button', { name: /Day 2: Upper A/ })).toBeVisible()
  await user.click(screen.getByRole('button', { name: /Day 2: Upper A/ }))
  expect(screen.getByRole('heading', { name: 'Upper A' })).toBeVisible()
  expect(screen.getByText(/Another routine · Day 2/)).toBeVisible()
  expect(screen.getByRole('button', { name: /bodyweight-squat/ })).toBeVisible()
  expect(screen.queryByText(/Monday|Wednesday/)).not.toBeInTheDocument()
})
test('one exercise expands at a time; names/order, independent actual targets and table headings are preserved', async () => {
  const user = userEvent.setup(); setup(); await start(user)
  const cards = screen.getAllByRole('button', { expanded: false })
  expect(cards.map(card => card.textContent)).toEqual([expect.stringContaining('Hip Thrust'), expect.stringContaining('RDLs')])
  await user.click(cards[0])
  expect(screen.getByRole('table', { name: 'Actual performance for Hip Thrust' })).toBeVisible()
  for (const title of ['Set', 'Weight', 'Reps']) expect(screen.getByRole('columnheader', { name: title })).toBeVisible()
  expect(screen.queryByRole('columnheader', { name: 'Done' })).not.toBeInTheDocument()
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  expect(screen.queryByLabelText('Set 1 weight')).not.toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Add set' }))
  expect(screen.getByLabelText('Set 1 weight')).toHaveValue(null)
  expect(screen.getByLabelText('Set 1 reps')).toHaveValue(null)
  await user.type(screen.getByLabelText('Set 1 reps'), '8')
  await user.click(cards[1])
  expect(screen.queryByRole('table', { name: /Hip Thrust/ })).not.toBeInTheDocument()
  expect(screen.getAllByRole('button', { expanded: true })).toHaveLength(1)
  await user.click(cards[0])
  expect(screen.getByLabelText('Set 1 reps')).toHaveValue(8)
  await user.click(cards[0])
  expect(screen.queryByRole('table')).not.toBeInTheDocument()
})
test('adding a set logs performed work immediately; editing and kg/lb conversion need no completion check', async () => {
  const user = userEvent.setup(); setup(); await start(user)
  await user.click(screen.getByRole('button', { name: /Hip Thrust/ }))
  expect(screen.getByText('0 sets logged', { selector: 'span.number' })).toBeVisible()
  await user.click(screen.getByRole('button', { name: 'Add set' }))
  expect(screen.getByText('1 set logged', { selector: 'span.number' })).toBeVisible()
  await user.type(screen.getByLabelText('Set 1 reps'), '8')
  await user.type(screen.getByLabelText('Set 1 weight'), '20')
  await user.click(screen.getByRole('button', { name: 'Add set' }))
  await user.type(screen.getByLabelText('Set 2 reps'), '6')
  await user.type(screen.getByLabelText('Set 2 weight'), '25')
  expect(screen.getByText('2 sets logged', { selector: 'span.number' })).toBeVisible()
  await user.selectOptions(screen.getByLabelText('Set 1 weight unit'), 'lb')
  expect(screen.getByLabelText('Set 1 weight')).toHaveValue(44.092452)
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  expect(screen.getByText('2 sets logged', { selector: 'span.number' })).toBeVisible()
  await user.selectOptions(screen.getByLabelText('Set 1 weight unit'), 'kg')
  expect(screen.getByLabelText('Set 1 weight')).toHaveValue(20)
  expect(screen.getByLabelText('Set 2 weight')).toHaveValue(25)
  expect(screen.getByLabelText('Set 2 reps')).toHaveValue(6)
  expect(routine.document.days[0].exercises[0].planned_sets![0].load_kg).toBe(30)
})
