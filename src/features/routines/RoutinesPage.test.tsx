test("Today's Workout is separate from saved plans, local-only, and cleared on account change", async () => {
  const user = userEvent.setup(), before = structuredClone(testDocument), view = page(true)
  expect(await screen.findByRole('heading', { name: "Today's Workout" })).toBeVisible()
  expect(screen.getByRole('heading', { name: /Active routines/ })).toBeVisible()
  await user.selectOptions(screen.getByLabelText('Choose a saved routine'), saved.id)
  await user.click(screen.getByRole('button', { name: 'Day 1: Full body' }))
  await user.click(screen.getByRole('button', { name: /bodyweight-squat/ }))
  await user.click(screen.getByRole('button', { name: 'Add set' }))
  await user.type(screen.getByLabelText('Set 1 reps'), '8')
  await user.type(screen.getByLabelText('Set 1 weight'), '20')
  expect(mocks.save).not.toHaveBeenCalled()
  expect(mocks.archive).not.toHaveBeenCalled()
  expect(mocks.delete).not.toHaveBeenCalled()
  expect(testDocument).toEqual(before)
  // Opening/cancelling the routine editor must not discard today's local draft.
  await user.click(screen.getByRole('button', { name: 'Edit My training plan' }))
  await user.click(screen.getByRole('button', { name: 'Cancel' }))
  expect(screen.getByLabelText('Set 1 reps')).toHaveValue(8)
  mocks.user = 'user-b'
  mocks.load.mockResolvedValue({ ...workspace(), routines: [] })
  view.rerender(routing(true))
  expect(await screen.findByText("Save a routine to start today's workout.")).toBeVisible()
  expect(screen.queryByLabelText('Set 1 reps')).not.toBeInTheDocument()
  expect(mocks.load).toHaveBeenLastCalledWith(mocks.client, 'user-b')
})
