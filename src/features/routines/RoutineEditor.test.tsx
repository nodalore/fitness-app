test('Add Exercise appends multiple exercises once each, clears targets, and saves the whole session', async () => {
  const initial = fresh(), save = vi.fn().mockResolvedValue(undefined), user = userEvent.setup()
  render(<RoutineEditor initial={initial} catalog={[]} onSave={save} onCancel={() => {}} />)
  await user.type(screen.getByLabelText('Routine name'), 'My plan')
  await user.type(screen.getByLabelText('Workout/session name'), 'Pull')
  for (const name of ['Cable row', 'Hammer curl', 'Farmer carry']) {
    await user.type(screen.getByLabelText('Exercise name'), name)
    await user.click(screen.getByRole('button', { name: 'Add Set' }))
    await user.type(screen.getByLabelText('Set 1 reps'), '8')
    await user.type(screen.getByLabelText('Set 1 planned weight'), '20')
    await user.click(screen.getByRole('button', { name: 'Add Exercise' }))
    expect(screen.getByLabelText('Exercise name')).toHaveValue('')
    expect(screen.getByLabelText('Number of sets')).toHaveValue(0)
    expect(screen.queryByLabelText('Set 1 reps')).not.toBeInTheDocument()
  }
  expect(within(added()!).getAllByRole('listitem')).toHaveLength(3)
  await user.click(screen.getByRole('button', { name: 'Add Exercise' }))
  expect(within(added()!).getAllByRole('listitem')).toHaveLength(3)
  await user.click(screen.getByRole('button', { name: 'Save Routine' }))
  expect(save).toHaveBeenCalledTimes(1)
  expect(save.mock.calls[0][0].days[0].exercises).toEqual(['Cable row', 'Hammer curl', 'Farmer carry'].map(name => ({
    ...blankExercise(name), planned_sets: [{ reps: 8, load_kg: 20, entered_unit: 'kg' }],
  })))
  expect(initial).toEqual(fresh())
})

